import sys

# Значения, зашитые в
# дистрибутив: конечный
# пользователь получает
# только файл ПО (exe),
# поэтому адрес головного
# сервера встроен в само
# приложение. Токены
# брокера НЕ зашиваются:
# они у каждого
# пользователя свои и
# берутся из настроек
# счёта. При запуске из
# исходников (dev/тесты)
# эти значения НЕ
# применяются — там
# по-прежнему работает
# .env, а переменные
# окружения всегда имеют
# приоритет и в exe.

# Адрес ESMHeadServer.exe
# для готовых сборок (порт
# головы по умолчанию:
# 8200).
EMBEDDED_HEAD_SERVER_URL = (
    "http://45.66.8.22:8200"
)

EMBEDDED_HEAD_SERVER_ENABLED = (
    True
)


def is_packaged_build() -> bool:
    # True только внутри
    # PyInstaller-сборки.
    return bool(
        getattr(
            sys,
            "frozen",
            False,
        )
    )
